export function normalizeLang(lang) {
  const s = String(lang || '').trim();
  if (s === 'ja' || s === 'en' || s === 'zh-TW') return s;
  return 'zh-TW';
}

export function getLanguage() {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === 'zh-TW' || saved === 'ja' || saved === 'en') return saved;
  const nav = String(navigator.language || '').toLowerCase();
  if (nav.startsWith('ja')) return 'ja';
  if (nav.startsWith('en')) return 'en';
  return 'zh-TW';
}

export function setLanguage(lang) {
  const normalized = normalizeLang(lang);
  localStorage.setItem(LANG_KEY, normalized);
  return normalized;
}

export function getLanguageMeta(lang) {
  const code = normalizeLang(lang || getLanguage());
  return LANGUAGES.find((l) => l.code === code) || LANGUAGES[0];
}

export function t(key, vars = null) {
  const lang = getLanguage();
  const dict = MESSAGES[lang] || MESSAGES['zh-TW'];
  let text = dict[key] !== undefined ? dict[key] : (MESSAGES['zh-TW'][key] || key);
  if (vars && typeof vars === 'object') {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return text;
}

export function applyDomTranslations() {
  const lang = getLanguage();
  const meta = getLanguageMeta(lang);
  document.documentElement.lang = meta.htmlLang;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.dataset.i18nPlaceholder;
    if (key) el.placeholder = t(key);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.dataset.i18nTitle;
    if (key) el.title = t(key);
  });
}
